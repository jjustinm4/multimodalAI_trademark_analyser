import { useState } from 'react'

// Inline markdown: **bold**, _italic_ / *italic*, `code`. Builds React nodes, no innerHTML.
function inline(text, keyBase) {
  const parts = []
  const re = /(\*\*[^*]+\*\*|`[^`]+`|_[^_]+_|\*[^*]+\*)/g
  let last = 0
  let m
  let i = 0
  while ((m = re.exec(text))) {
    if (m.index > last) parts.push(text.slice(last, m.index))
    const tok = m[0]
    const k = `${keyBase}-${i++}`
    if (tok.startsWith('**')) parts.push(<strong key={k}>{tok.slice(2, -2)}</strong>)
    else if (tok.startsWith('`')) parts.push(<code key={k} className="rounded bg-slate-100 px-1 font-mono text-[0.9em] dark:bg-slate-800">{tok.slice(1, -1)}</code>)
    else parts.push(<em key={k}>{tok.slice(1, -1)}</em>)
    last = m.index + tok.length
  }
  if (last < text.length) parts.push(text.slice(last))
  return parts
}

// Block markdown: headings, bullet and numbered lists, paragraphs.
function renderMarkdown(md) {
  const lines = md.replace(/\r/g, '').split('\n')
  const blocks = []
  let list = null
  let para = []
  const flushPara = () => {
    if (para.length) blocks.push({ type: 'p', text: para.join(' ') })
    para = []
  }
  const flushList = () => {
    if (list) blocks.push(list)
    list = null
  }
  for (const raw of lines) {
    const line = raw.trimEnd()
    const h = line.match(/^(#{1,4})\s+(.*)$/)
    const ul = line.match(/^\s*[-*•]\s+(.*)$/)
    const ol = line.match(/^\s*(\d+)[.)]\s+(.*)$/)
    if (h) { flushPara(); flushList(); blocks.push({ type: 'h', level: h[1].length, text: h[2] }) }
    else if (ul || ol) {
      flushPara()
      const type = ul ? 'ul' : 'ol'
      if (!list || list.type !== type) { flushList(); list = { type, items: [] } }
      list.items.push(ul ? ul[1] : ol[2])
    } else if (!line.trim()) { flushPara(); flushList() }
    else if (list && /^\s{2,}/.test(raw)) { list.items[list.items.length - 1] += ' ' + line.trim() }
    else { flushList(); para.push(line.trim()) }
  }
  flushPara(); flushList()

  return blocks.map((b, i) => {
    if (b.type === 'h') {
      const cls = b.level <= 2
        ? 'mt-6 mb-2 border-b border-slate-200 pb-1 text-base font-semibold first:mt-0 dark:border-slate-800'
        : 'mt-4 mb-1 text-sm font-semibold'
      return <h3 key={i} className={cls}>{inline(b.text, i)}</h3>
    }
    if (b.type === 'ul') return <ul key={i} className="my-2 list-disc space-y-1 pl-5">{b.items.map((t, j) => <li key={j}>{inline(t, `${i}-${j}`)}</li>)}</ul>
    if (b.type === 'ol') return <ol key={i} className="my-2 list-decimal space-y-1 pl-5">{b.items.map((t, j) => <li key={j}>{inline(t, `${i}-${j}`)}</li>)}</ol>
    return <p key={i} className="my-2">{inline(b.text, i)}</p>
  })
}

export default function ReportPanel({ report, source, warning }) {
  const [copied, setCopied] = useState(false)
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(report)
    } catch (e) {
      // Clipboard API needs a secure context; fall back for plain-http hosts.
      const ta = document.createElement('textarea')
      ta.value = report
      document.body.appendChild(ta)
      ta.select()
      document.execCommand('copy')
      ta.remove()
    }
    setCopied(true)
    setTimeout(() => setCopied(false), 1800)
  }

  return (
    <section className="panel overflow-hidden">
      <div className="flex items-center justify-between border-b border-slate-200 px-5 py-3 dark:border-slate-800">
        <h2 className="panel-title">Examination report</h2>
        <button onClick={copy} className="btn-ghost px-3 py-1.5 text-xs">{copied ? 'Copied' : 'Copy to clipboard'}</button>
      </div>
      {source === 'fallback' ? (
        <div className="border-b border-yellow-200 bg-yellow-50 px-5 py-2 text-xs text-yellow-900 dark:border-yellow-900/50 dark:bg-yellow-500/10 dark:text-yellow-200">
          ⚠ {warning || 'Language model unavailable. This is a template report.'}
        </div>
      ) : (
        <div className="border-b border-slate-200 bg-slate-50 px-5 py-2 text-xs text-slate-500 dark:border-slate-800 dark:bg-slate-800/40 dark:text-slate-400">
          Generated by AI — review before signing
        </div>
      )}
      <article className="max-w-4xl px-6 py-5 text-sm leading-relaxed text-slate-800 dark:text-slate-200">
        {renderMarkdown(report)}
      </article>
    </section>
  )
}
